#pragma once

/// @file tag_families.hpp
/// @brief Published AprilTag family tables (WP-13.7).
///
/// The seven families supported here are interoperability data: users print
/// the standard tags, so these tables must equal the published ones exactly.
/// They are NOT produced by alphashape's own code generator; a script
/// (`tools/markers/import_apriltag_families.py`) extracts the tables and the
/// per-bit layout from the published AprilRobotics/apriltag sources
/// (BSD-2-Clause; the copyright notice is reproduced in the generated
/// `tag_family_data.cpp` and in every fixture). See THIRD_PARTY_NOTICES for
/// the attribution entry.
///
/// ## Bit layout
///
/// `bit_xy[i]` is the published cell of bit `i`, where cell `(x, y)` covers
/// `[x, x+1] x [y, y+1]` in a coordinate system whose `width_at_border`
/// square spans `[0, width_at_border]`. Tag-frame coordinates used by the
/// decoder are `u = 2*(x+0.5)/width_at_border - 1` (likewise `v`), so the
/// border square is `[-1, 1]` and a cell's centre is at `bit_xy + 0.5` in
/// cell units. The published `total_width` grid adds the white margin (plain
/// families) or the surrounding payload ring (reversed-border families); the
/// decoder only needs `total_width/width_at_border` to interpret the
/// candidate quad of a reversed-border family.
///
/// `codes[id]` is the published 64-bit code. Bit `i` of the layout (most
/// significant bit first, i.e. code bit `bits-1-i`) is set when the printed
/// cell is white.
///
/// The tables cannot be regenerated by a greedy lexicode: the published
/// generator's pseudo-random search order is not reproducible. The tests
/// instead compare the C++ tables against the checked-in fixtures
/// (`FamilyTablesMatchPublished`) and verify the stated minimum Hamming
/// distance (`FamilyMinHamming`).

#include <cstdint>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

namespace alphashape {

/// One published family, unpacked. `codes` and `bit_xy` are copied out of the
/// generated tables so callers never depend on the generated header.
struct TagFamily {
    std::string name;                            ///< "16h5", "36h11", ...
    int bits = 0;                                ///< nbits (16, 25, 36, ...).
    int min_hamming = 0;                         ///< Published `h`.
    int total_width = 0;                         ///< Full printed grid width.
    int width_at_border = 0;                     ///< Border-square width.
    bool reversed_border = false;                ///< Border is white, not black.
    std::vector<std::uint64_t> codes;            ///< Published codes, id = index.
    std::vector<std::pair<int, int>> bit_xy;     ///< Published bit layout.
};

/// The supported families, in the generated table order.
enum class AprilTagFamily {
    Tag16h5 = 0,
    Tag25h9,
    Tag36h10,
    Tag36h11,
    Circle21h7,
    Standard41h12,
    Standard52h13,
};

/// Number of entries in `AprilTagFamily`.
inline constexpr int kAprilTagFamilyCount = 7;

/// Table for `family`.
const TagFamily& tag_family(AprilTagFamily family);

/// Parse "16h5", "tag16h5", "Standard41h12" (case-insensitive, an optional
/// "tag" prefix and underscores/dashes are ignored). Returns nullopt for an
/// unknown name.
std::optional<AprilTagFamily> parse_tag_family(std::string_view name);

/// Largest error-correction radius whose random-word acceptance stays below
/// 1e-4 (and never above `(min_hamming - 1) / 2`). See the table in
/// apriltag_decoder.hpp for the underlying fractions. 16h5 cannot reach 1e-4
/// even at radius 0 and is an inherently weak family.
int default_max_hamming(const TagFamily& family);

/// Convenience overload.
int default_max_hamming(AprilTagFamily family);

/// Rotate a layout-order word by one 90-degree step about the tag centre. Bit
/// `i` moves to the position that cell `i` occupies after the rotation. The
/// operation is a permutation of the layout and is its own sequence of four
/// steps back to the start.
std::uint64_t rotate_tag_word(std::uint64_t word, const TagFamily& family);

/// Smallest and largest Hamming weight among the published codes. The decoder
/// uses them to reject a constant payload reading (for example a solid dark
/// square) before doing the table search.
int min_code_weight(const TagFamily& family);
int max_code_weight(const TagFamily& family);

}  // namespace alphashape
