// WP-12.2: the CoordinateSystem value type and the 48-entry built-in list.
//
// Two things are deliberately kept apart. Semantic checks (equivalence,
// round-trip) go through PROJ, because WKT2 text is not a stable identity: the
// same EPSG code renders differently between PROJ data releases (WGS 84's
// ensemble gains a member every few years). Textual checks compare against
// fixtures in tests/fixtures/crs/ after normalisation, so the golden files
// still pin the datum, the projection parameters and the axis definitions.
//
// The built-in list is curated (§4.6), so its size and its names are part of
// the contract; NameMatchesProj re-derives every name from the raw PROJ API
// rather than from our own table.

