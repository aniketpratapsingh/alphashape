namespace fs = std::filesystem;

const fs::path kFixtureDir = fs::path(__FILE__).parent_path() / "fixtures" / "crs";

/// The golden skeleton per EPSG code, read from
/// tests/fixtures/crs/builtin_wkt_skeletons.txt (generated by the tool beside
/// it). Empty when the file is missing, which fails the assertion that uses it
/// with a message saying so rather than silently passing.
std::map<int, std::string> read_skeletons() {
    std::map<int, std::string> skeletons;
    std::ifstream in(kFixtureDir / "builtin_wkt_skeletons.txt");
    std::string line;
    while (std::getline(in, line)) {
        if (line.empty() || line.front() == '#') {
            continue;
        }
        const std::size_t space = line.find(' ');
        if (space == std::string::npos) {
            continue;
        }
        skeletons[std::stoi(line.substr(0, space))] = line.substr(space + 1);
    }
    return skeletons;
}

/// The construct each CRS kind must be serialised as (WKT2:2019 keyword).
const char* wkt_construct(CrsKind kind) {
    switch (kind) {
        case CrsKind::Geographic2D:
        case CrsKind::Geographic3D:
            return "GEOGCRS[";
        case CrsKind::Projected:
            return "PROJCRS[";
        case CrsKind::Geocentric:
            return "GEODCRS[";
        case CrsKind::Vertical:
            return "VERTCRS[";
        case CrsKind::Compound:
            return "COMPOUNDCRS[";
        case CrsKind::Local:
            return "ENGCRS[";
    }
    return "";
}

