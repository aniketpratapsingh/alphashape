TEST(Crs, LocalIsUnset) {
    const CoordinateSystem by_default;
    const CoordinateSystem local = CoordinateSystem::local();

    EXPECT_FALSE(by_default.is_set());
    EXPECT_TRUE(by_default.is_local());
    EXPECT_EQ(by_default.epsg(), 0);
    EXPECT_EQ(by_default.name(), "LOCAL");
    EXPECT_EQ(by_default.auth_name(), "LOCAL");
    EXPECT_EQ(by_default.auth_code(), "");
    EXPECT_EQ(by_default.kind(), CrsKind::Local);
    EXPECT_FALSE(by_default.to_wkt().empty());
    EXPECT_FALSE(by_default.vertical().has_value());
    EXPECT_EQ(by_default, local);
    EXPECT_FALSE(local.is_set());

    // Local is its own CRS and not equal to any real one.
    EXPECT_NE(local, CoordinateSystem::from_epsg(4326));
    EXPECT_FALSE(local.is_equivalent_to(CoordinateSystem::from_epsg(4326)));
    // Two local frames are the same frame.
    EXPECT_TRUE(local.is_equivalent_to(CoordinateSystem::local()));
}

TEST(Crs, FromEpsgKnown) {
    const CoordinateSystem utm = CoordinateSystem::from_epsg(32633);

    EXPECT_TRUE(utm.is_set());
    EXPECT_FALSE(utm.is_local());
    EXPECT_EQ(utm.epsg(), 32633);
    EXPECT_EQ(utm.name(), "WGS 84 / UTM zone 33N");
    EXPECT_EQ(utm.auth_name(), "EPSG");
    EXPECT_EQ(utm.auth_code(), "32633");
    EXPECT_EQ(utm.kind(), CrsKind::Projected);

    const std::string wkt = utm.to_wkt();
    EXPECT_EQ(wkt.find("PROJCRS[\"WGS 84 / UTM zone 33N\""), 0U);
    EXPECT_EQ(wkt.find('\n'), std::string::npos) << "WKT must be single-line for XML attributes";
    EXPECT_NE(wkt.find("ID[\"EPSG\",32633]"), std::string::npos);

    const std::string proj = utm.to_proj4();
    EXPECT_NE(proj.find("+proj=utm"), std::string::npos);
    EXPECT_NE(proj.find("+zone=33"), std::string::npos);

    // The other two WGS 84 slots report their own kinds.
    EXPECT_EQ(CoordinateSystem::from_epsg(4326).kind(), CrsKind::Geographic2D);
    EXPECT_EQ(CoordinateSystem::from_epsg(4979).kind(), CrsKind::Geographic3D);
    EXPECT_EQ(CoordinateSystem::from_epsg(4978).kind(), CrsKind::Geocentric);
}

TEST(Crs, FromEpsgUnknownThrows) {
    EXPECT_THROW(CoordinateSystem::from_epsg(999999), ValueError);
    EXPECT_THROW(CoordinateSystem::from_epsg(0), ValueError);
    EXPECT_THROW(CoordinateSystem::from_epsg(-4326), ValueError);

    // The message names the code, so a log line is actionable.
    try {
        static_cast<void>(CoordinateSystem::from_epsg(999999));
        FAIL() << "expected ValueError";
    } catch (const ValueError& error) {
        EXPECT_NE(std::string(error.what()).find("999999"), std::string::npos);
    }

    // A coordinate operation is not a CRS: a PROJ string without +type=crs is
    // rejected rather than silently becoming something else.
    EXPECT_THROW(CoordinateSystem::from_wkt("+proj=utm +zone=33"), ValueError);
    EXPECT_THROW(CoordinateSystem::from_wkt("not wkt at all"), ValueError);
    EXPECT_THROW(CoordinateSystem::from_wkt(""), ValueError);
    EXPECT_THROW(CoordinateSystem::from_proj(""), ValueError);
}

TEST(Crs, WktRoundTrip) {
    std::size_t checked = 0;
    for (const BuiltinCrs& entry : builtin_crs_list()) {
        SCOPED_TRACE("EPSG:" + std::to_string(entry.epsg));
        const CoordinateSystem original = CoordinateSystem::from_epsg(entry.epsg);
        const std::string wkt = original.to_wkt();
        ASSERT_FALSE(wkt.empty());
        ASSERT_EQ(wkt.find('\n'), std::string::npos);

        CoordinateSystem parsed;
        ASSERT_NO_THROW(parsed = CoordinateSystem::from_wkt(wkt));

        // Identity survives: the re-parsed CRS carries the same authority code
        // and name, and PROJ confirms nothing semantic was lost.
        EXPECT_EQ(parsed, original);
        EXPECT_TRUE(parsed.is_equivalent_to(original));
        EXPECT_EQ(parsed.epsg(), entry.epsg);
        EXPECT_EQ(parsed.name(), entry.name);
        EXPECT_EQ(parsed.kind(), entry.kind);

        // The textual form reaches a fixed point at the second generation.
        // PROJ is not idempotent for every CRS on the first pass — EPSG:3857
        // loses its ENSEMBLE (becomes a DATUM) and its CONVERSION name when
        // re-parsed, so the first reparse is canonical-but-different — but a
        // value that has been through from_wkt once must reproduce itself.
        const CoordinateSystem twice = CoordinateSystem::from_wkt(parsed.to_wkt());
        EXPECT_EQ(twice.to_wkt(), parsed.to_wkt()) << "WKT generation is not stable";
        EXPECT_EQ(twice, parsed);
        ++checked;
    }
    EXPECT_EQ(checked, 48U) << "the built-in list is the round-trip corpus (§4.6)";
}

TEST(Crs, EpsgRoundTrip) {
    // Every built-in with a code must rebuild from that code to an equivalent
    // CRS; the 48 entries all have one, so this also proves the codes are live
    // in the installed proj.db rather than merely listed.
    std::size_t with_code = 0;
    for (const BuiltinCrs& entry : builtin_crs_list()) {
        SCOPED_TRACE("EPSG:" + std::to_string(entry.epsg));
        ASSERT_GT(entry.epsg, 0);
        const CoordinateSystem from_code = CoordinateSystem::from_epsg(entry.epsg);
        EXPECT_EQ(from_code.epsg(), entry.epsg);
        // By name, in list order: unique for every entry but the WGS 84 trio,
        // where 4326 comes first (§4.6 order).
        EXPECT_EQ(from_code.from_name(entry.name).epsg(),
                  entry.epsg == 4979 || entry.epsg == 4978 ? 4326 : entry.epsg);
        // Via WKT and back to the same code, both directions of the triangle.
        const CoordinateSystem from_text = CoordinateSystem::from_wkt(from_code.to_wkt());
        EXPECT_EQ(from_text.epsg(), entry.epsg);
        EXPECT_TRUE(from_text.is_equivalent_to(from_code, /*ignore_axis_order=*/false));
        ++with_code;
    }
    EXPECT_EQ(with_code, 48U);
}

TEST(Crs, EquivalenceIgnoresAxisOrder) {
    // EPSG:4326 is authority axis order lat,lon. The same WGS 84 geodetic CRS
    // written lon,lat (what every GIS user means by "WGS 84") is a different
    // WKT string and different bytes, but the same CRS.
    const CoordinateSystem authority = CoordinateSystem::from_epsg(4326);
    const CoordinateSystem lon_lat = CoordinateSystem::from_wkt(
        "GEOGCRS[\"WGS 84\","
        "DATUM[\"World Geodetic System 1984\","
        "ELLIPSOID[\"WGS 84\",6378137,298.257223563,LENGTHUNIT[\"metre\",1]]],"
        "PRIMEM[\"Greenwich\",0,ANGLEUNIT[\"degree\",0.0174532925199433]],"
        "CS[ellipsoidal,2],"
        "AXIS[\"longitude (Lon)\",east,ORDER[1],ANGLEUNIT[\"degree\",0.0174532925199433]],"
        "AXIS[\"latitude (Lat)\",north,ORDER[2],ANGLEUNIT[\"degree\",0.0174532925199433]]]");

    EXPECT_NE(authority.to_wkt(), lon_lat.to_wkt());
    EXPECT_NE(authority, lon_lat) << "string identity is axis-order sensitive by design";
    EXPECT_TRUE(authority.is_equivalent_to(lon_lat, /*ignore_axis_order=*/true));
    EXPECT_FALSE(authority.is_equivalent_to(lon_lat, /*ignore_axis_order=*/false));

    // Axis order is the exception: a different datum is never equivalent.
    EXPECT_FALSE(authority.is_equivalent_to(CoordinateSystem::from_epsg(4269)));
    // Nor is a projected CRS equivalent to its base geographic CRS.
    EXPECT_FALSE(authority.is_equivalent_to(CoordinateSystem::from_epsg(32633)));

    // Same CRS, two spellings of the same definition (PROJ string vs code).
    const CoordinateSystem from_proj_string =
        CoordinateSystem::from_proj("+proj=utm +zone=33 +datum=WGS84 +units=m");
    EXPECT_FALSE(from_proj_string.is_set() == false);
    EXPECT_EQ(from_proj_string.epsg(), 0) << "a PROJ string carries no authority code";
    EXPECT_TRUE(from_proj_string.is_equivalent_to(CoordinateSystem::from_epsg(32633)));
}

TEST(Crs, BuiltinListHas48Entries) {
    const std::vector<BuiltinCrs>& list = builtin_crs_list();
    ASSERT_EQ(list.size(), 48U);

    std::set<int> codes;
    for (const BuiltinCrs& entry : list) {
        EXPECT_GT(entry.epsg, 0);
        EXPECT_FALSE(entry.name.empty());
        EXPECT_TRUE(codes.insert(entry.epsg).second) << "duplicate code " << entry.epsg;
    }
    // Codes are unique; names are not, because PROJ gives 4326, 4979 and 4978
    // the same name. from_name() resolves an ambiguous name to the first entry.
    std::map<std::string, int> first_with_name;
    std::set<std::string> ambiguous;
    for (const BuiltinCrs& entry : list) {
        const auto inserted = first_with_name.emplace(entry.name, entry.epsg);
        if (!inserted.second) {
            ambiguous.insert(entry.name);
        }
    }
    EXPECT_EQ(ambiguous, std::set<std::string>({"WGS 84"}));

    // The named categories of §4.6 must each be present.
    for (int required : {4326, 4978, 4979, 32601, 32619, 32701, 32705, 4258, 25832, 3035,
                         4269, 26911, 26919, 5070, 7844, 7855, 3006, 27700, 2056, 4167,
                         2193, 4674, 31983, 4490, 4548, 3857, 4230}) {
        EXPECT_TRUE(codes.count(required) == 1U) << "EPSG:" << required << " missing";
    }

    // Names and the name list agree with the entries, in order.
    const std::vector<std::string> name_list = builtin_crs_names();
    ASSERT_EQ(name_list.size(), list.size());
    for (std::size_t i = 0; i < list.size(); ++i) {
        EXPECT_EQ(name_list[i], list[i].name);
        EXPECT_EQ(CoordinateSystem::from_name(list[i].name).epsg(),
                  first_with_name.at(list[i].name))
            << "from_name resolves " << list[i].name << " to the first entry with that name";
    }
    EXPECT_EQ(CoordinateSystem::from_name("LOCAL"), CoordinateSystem::local());
    EXPECT_THROW(CoordinateSystem::from_name("Nowhere / UTM zone 0"), ValueError);
}

TEST(Crs, NameMatchesProj) {
    // The list is not a name table: every name comes from proj_get_name, and
    // every kind from proj_get_type. Ask PROJ directly and compare.
    PJ_CONTEXT* ctx = thread_context();
    ASSERT_NE(ctx, nullptr);
    for (const BuiltinCrs& entry : builtin_crs_list()) {
        SCOPED_TRACE("EPSG:" + std::to_string(entry.epsg));
        const std::string text = "EPSG:" + std::to_string(entry.epsg);
        PJ* pj = proj_create(ctx, text.c_str());
        ASSERT_NE(pj, nullptr);
        ASSERT_TRUE(proj_is_crs(pj) != 0);

        const char* name = proj_get_name(pj);
        ASSERT_NE(name, nullptr);
        EXPECT_EQ(entry.name, std::string(name));
        EXPECT_EQ(CoordinateSystem::from_epsg(entry.epsg).name(), std::string(name));

        const char* auth = proj_get_id_auth_name(pj, 0);
        const char* code = proj_get_id_code(pj, 0);
        ASSERT_NE(auth, nullptr);
        ASSERT_NE(code, nullptr);
        EXPECT_EQ(std::string(auth), "EPSG");
        EXPECT_EQ(std::string(code), std::to_string(entry.epsg));

        proj_destroy(pj);
    }
}

TEST(Crs, WktMatchesGoldenFixture) {
    // The textual pin: every built-in's normalised WKT equals the checked-in
    // skeleton. Semantic round-trip (WktRoundTrip) proves nothing was lost;
    // this proves the datum, ellipsoid, projection parameters and axis
    // definitions are the ones the fixture recorded, so an accidental edit to
    // from_wkt/to_wkt or to the code table cannot pass unnoticed.
    const std::map<int, std::string> golden = read_skeletons();
    ASSERT_EQ(golden.size(), 48U)
        << "tests/fixtures/crs/builtin_wkt_skeletons.txt is missing or truncated; "
           "regenerate it with tests/fixtures/crs/make_skeletons.cpp";

    for (const BuiltinCrs& entry : builtin_crs_list()) {
        SCOPED_TRACE("EPSG:" + std::to_string(entry.epsg));
        const auto it = golden.find(entry.epsg);
        ASSERT_NE(it, golden.end()) << "no golden skeleton for this code";
        const CoordinateSystem cs = CoordinateSystem::from_epsg(entry.epsg);
        EXPECT_EQ(crs_fixture::wkt_skeleton(cs.to_wkt()), it->second);
        // The construct is the kind: a mismatched keyword would mean
        // kind_from_proj() and the WKT disagree.
        EXPECT_EQ(cs.to_wkt().rfind(wkt_construct(cs.kind()), 0), 0U)
            << "WKT construct does not match the reported kind";
    }
}

TEST(Crs, WktDialectsAndProj4) {
    const CoordinateSystem utm = CoordinateSystem::from_epsg(32633);

    // WKT2:2019 is canonical and stored; the 2015 flavour differs textually but
    // parses back to the same CRS.
    const std::string wkt2019 = utm.to_wkt(WktDialect::Wkt2_2019);
    const std::string wkt2015 = utm.to_wkt(WktDialect::Wkt2_2015);
    EXPECT_FALSE(wkt2015.empty());
    EXPECT_TRUE(CoordinateSystem::from_wkt(wkt2015).is_equivalent_to(utm));

    // WKT1_GDAL is lossy (no ensembles, no USAGE) but still rebuilds the same
    // projected CRS; a great deal of third-party data is written this way.
    const std::string wkt1 = utm.to_wkt(WktDialect::Wkt1_GDAL);
    EXPECT_EQ(wkt1.rfind("PROJCS[", 0), 0U);
    EXPECT_TRUE(CoordinateSystem::from_wkt(wkt1).is_equivalent_to(utm));
    EXPECT_FALSE(utm.to_wkt(WktDialect::Wkt1_ESRI).empty());

    EXPECT_EQ(std::string(wkt_dialect_name(WktDialect::Wkt2_2019)), "WKT2:2019");
    EXPECT_EQ(std::string(wkt_dialect_name(WktDialect::Wkt1_GDAL)), "WKT1_GDAL");
    EXPECT_EQ(std::string(crs_kind_name(CrsKind::Projected)), "projected");
    EXPECT_EQ(std::string(crs_kind_name(CrsKind::Geocentric)), "geocentric");

    // to_proj4 round-trips through from_proj to an equivalent CRS.
    const std::string proj4 = utm.to_proj4();
    ASSERT_FALSE(proj4.empty());
    EXPECT_TRUE(CoordinateSystem::from_proj(proj4).is_equivalent_to(utm));
    // The local frame has neither a PROJ string nor an authority.
    EXPECT_TRUE(CoordinateSystem::local().to_proj4().empty());
}

TEST(Crs, VerticalComponent) {
    // §4.2/§4.5: the vertical component is carried by the value type; applying
    // a geoid shift is WP-12.5, not here.
    const CoordinateSystem horizontal = CoordinateSystem::from_epsg(32633);
    EXPECT_FALSE(horizontal.vertical().has_value());

    VerticalCrs egm2008;
    egm2008.kind = VerticalCrs::Kind::GeoidModel;
    egm2008.name = "EGM2008 height";
    egm2008.grid = "us_nga_egm08_25.tif";
    EXPECT_TRUE(egm2008.is_set());

    const CoordinateSystem with_geoid = horizontal.with_vertical(egm2008);
    ASSERT_TRUE(with_geoid.vertical().has_value());
    EXPECT_EQ(with_geoid.vertical()->grid, "us_nga_egm08_25.tif");
    // The horizontal definition is untouched.
    EXPECT_EQ(with_geoid.epsg(), 32633);
    EXPECT_EQ(with_geoid.to_wkt(), horizontal.to_wkt());
    // A vertical component is part of identity: dropping it is a different CRS.
    EXPECT_NE(with_geoid, horizontal);
    EXPECT_FALSE(with_geoid.is_equivalent_to(horizontal));
    EXPECT_TRUE(with_geoid.is_equivalent_to(horizontal.with_vertical(egm2008)));

    // An ellipsoidal (unset) vertical clears it again.
    const VerticalCrs ellipsoidal;
    EXPECT_FALSE(with_geoid.with_vertical(ellipsoidal).vertical().has_value());
    EXPECT_EQ(with_geoid.with_vertical(ellipsoidal), horizontal);

    // Copying is cheap and does not alias the vertical state.
    CoordinateSystem copy = with_geoid;
    copy = copy.with_vertical(VerticalCrs{});
    EXPECT_FALSE(copy.vertical().has_value());
    EXPECT_TRUE(with_geoid.vertical().has_value());
}

TEST(Crs, ChunkAndDocumentStoreCoordinateSystem) {
    // WP-12.2 stores the engine type on Chunk/Document while doc.xml keeps the
    // DTO. Assignment is a relabel: no data is transformed (§4.7).
    Document document;
    Chunk& chunk = document.workspace().add_chunk("c");

    EXPECT_FALSE(chunk.coordinate_system().is_set());
    EXPECT_TRUE(chunk.coordinate_system().is_local());

    chunk.set_coordinate_system(CoordinateSystem::from_epsg(32633));
    EXPECT_EQ(chunk.coordinate_system().epsg(), 32633);
    EXPECT_EQ(chunk.crs().epsg, 32633) << "the DTO mirrors the value for doc.xml";
    EXPECT_EQ(chunk.coordinate_system(), CoordinateSystem::from_epsg(32633));
    EXPECT_EQ(chunk.transform(), Transform::Identity()) << "no data was transformed";

    document.set_global_coordinate_system(CoordinateSystem::from_epsg(4326));
    EXPECT_EQ(document.global_coordinate_system().epsg(), 4326);
    EXPECT_EQ(document.global_crs().epsg, 4326);

    // Chunks and the document are independent slots.
    EXPECT_EQ(chunk.coordinate_system().epsg(), 32633);

    // A DTO with only an EPSG (the v1 project layout) reads as that CRS; one
    // with only WKT parses the WKT; an empty DTO is local.
    CRS from_code;
    from_code.epsg = 32633;
    EXPECT_EQ(static_cast<CoordinateSystem>(from_code).epsg(), 32633);
    CRS from_text;
    from_text.wkt = CoordinateSystem::from_epsg(4326).to_wkt();
    EXPECT_EQ(static_cast<CoordinateSystem>(from_text).epsg(), 4326);
    EXPECT_TRUE(static_cast<CoordinateSystem>(CRS{}).is_local());

    // And back: the DTO of a projected CRS carries both the code and the WKT.
    const CRS dto(CoordinateSystem::from_epsg(32633));
    EXPECT_EQ(dto.epsg, 32633);
    EXPECT_EQ(dto.wkt, CoordinateSystem::from_epsg(32633).to_wkt());
    // The local frame has no code and stores the LOCAL WKT.
    const CRS local_dto(CoordinateSystem::local());
    EXPECT_EQ(local_dto.epsg, 0);
    EXPECT_FALSE(local_dto.is_set());
}

