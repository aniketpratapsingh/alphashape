#!/bin/sh
# Regenerate tests/fixtures/crs/cs2cs_reference.csv for Crs.MatchesCs2cs
# (WP-12.3). The checked-in CSV is a fixture, not a build dependency: run this
# only when the reference really needs regenerating, and commit the result.
#
# Usage: tests/make_cs2cs_reference.sh [count] [output-csv]
#
# The source points come from an explicit 32-bit LCG so the file is
# reproducible; cs2cs is the reference implementation the test compares
# against. -f %.9f is required: PROJ's default formatting is closer to
# centimetres, which would hide a millimetre regression.
set -eu

count=${1:-20000}
here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
output=${2:-"$here/fixtures/crs/cs2cs_reference.csv"}

src=$(mktemp)
latlon=$(mktemp)
dst=$(mktemp)
trap 'rm -f "$src" "$latlon" "$dst"' EXIT

awk -v n="$count" 'BEGIN {
    state = 20201021
    for (i = 0; i < n; i++) {
        state = (16807 * state) % 2147483647; lon = 12.01 + (17.99 - 12.01) * state / 2147483647
        state = (16807 * state) % 2147483647; lat = 0.01 + (83.5 - 0.01) * state / 2147483647
        state = (16807 * state) % 2147483647; h = -150 + 4150 * state / 2147483647
        printf "%.12f,%.12f,%.6f\n", lon, lat, h
    }
}' >"$src"

# cs2cs honours the CRS's authority axis order, and EPSG:4326 is lat,lon: feed
# it latitude first, or every point lands somewhere else. The output columns
# keep the file's lon,lat order (the engine's x = east/lon convention).
awk -F, '{ printf "%.12f %.12f %.6f\n", $2, $1, $3 }' "$src" >"$latlon"
cs2cs -f %.9f EPSG:4326 EPSG:32633 <"$latlon" | tr '\t' ',' | tr ' ' ',' >"$dst"

{
    echo "# cs2cs reference for Crs.MatchesCs2cs: EPSG:4326 -> EPSG:32633"
    echo "# Generated by tests/make_cs2cs_reference.sh; do not edit by hand."
    echo "# Columns: src_lon,src_lat,src_h,dst_easting,dst_northing,dst_h (metres)"
    paste -d, "$src" "$dst"
} >"$output"

echo "wrote $(grep -vc '^#' "$output") rows to $output"
