#!/usr/bin/env python3
"""Compile design/system/tokens.json into the Qt style sheets.

QSS has no variables, so the sheets are generated: design/system/alphashape.qss.in is the
template and this script substitutes into it.

Template syntax
  $group.name        colour token, resolved against color.<theme> in tokens.json
                     (for example $surface.panel or $status.error)
  <<dark||light>>    literal text that differs per theme and is not a token
                     (the translucent hover overlays)

Each output starts with a header carrying the SHA-256 of tokens.json, so a stale sheet is
detectable. The viewport background/gradient/text colours are also emitted as a C++ header
(engine/src/apps/gui/theme/viewport_colors.hpp) so the painted viewport follows tokens.json.
Run with --check to verify the checked-in sheets are current (exit 1 if not).

Usage:
  compile_qss.py [--tokens FILE] [--template FILE] [--out-dir DIR] [--header FILE] [--check]
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

THEMES = ("dark", "light")
HEX = re.compile(r"#[0-9A-Fa-f]{6}")
PLACEHOLDER = re.compile(r"\$([A-Za-z][A-Za-z0-9]*(?:\.[A-Za-z][A-Za-z0-9]*)+)")
ALTERNATE = re.compile(r"<<(.*?)\|\|(.*?)>>")


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def raw_text(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def resolve(tokens: dict, theme: str, path: str) -> str:
    node = tokens["color"][theme]
    for part in path.split("."):
        if not isinstance(node, dict) or part not in node:
            raise KeyError("unknown token $%s in theme %s" % (path, theme))
        node = node[part]
    if not isinstance(node, str) or not HEX.fullmatch(node):
        raise ValueError("token $%s is not a #RRGGBB colour" % path)
    return node.upper()


def render(template: str, tokens: dict, tokens_sha256: str, theme: str) -> str:
    def alternate(match: "re.Match[str]") -> str:
        return match.group(1 if theme == "dark" else 2)

    body = ALTERNATE.sub(alternate, template)
    body = PLACEHOLDER.sub(lambda m: resolve(tokens, theme, m.group(1)), body)
    if "$" in body or "<<" in body or "||" in body:
        raise ValueError("unresolved placeholder left in the %s sheet" % theme)
    header = (
        "/* alphashape %s - generated by tools/theme/compile_qss.py from design/system/tokens.json."
        " Do not edit; change alphashape.qss.in or tokens.json. */\n"
        "/* tokens-sha256: %s */\n" % (theme, tokens_sha256)
    )
    return header + body


def render_header(tokens: dict, tokens_sha256: str) -> str:
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/theme/compile_qss.py from design/system/tokens.json - generated, do not edit.",
        "// tokens-sha256: %s" % tokens_sha256,
        "",
        "namespace alphashape::gui::viewport_colors {",
        "",
    ]
    for theme in THEMES:
        lines.append("namespace %s {" % theme)
        for name, path in (("background", "viewport.bg"),
                           ("gradient_to", "viewport.bgGradientTo"),
                           ("label", "viewport.pointCloud")):
            lines.append('inline constexpr const char* %s = "%s";' % (name, resolve(tokens, theme, path)))
        lines.append("}  // namespace %s" % theme)
        lines.append("")
    lines.append("}  // namespace alphashape::gui::viewport_colors")
    return "\n".join(lines) + "\n"


def main(argv: list) -> int:
    root = repo_root()
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--tokens", type=Path, default=root / "design/system/tokens.json")
    parser.add_argument("--template", type=Path, default=root / "design/system/alphashape.qss.in")
    parser.add_argument("--out-dir", type=Path, default=root / "design/system")
    parser.add_argument("--header", type=Path,
                        default=root / "engine/src/apps/gui/theme/viewport_colors.hpp")
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if an output file is missing or stale")
    args = parser.parse_args(argv)

    # Normalise line endings so a CRLF checkout (Windows autocrlf) hashes and compares the same.
    raw = args.tokens.read_bytes().replace(b"\r\n", b"\n")
    tokens = json.loads(raw.decode("utf-8"))
    digest = hashlib.sha256(raw).hexdigest()
    template = raw_text(args.template)

    stale = False
    for theme in THEMES:
        text = render(template, tokens, digest, theme)
        target = args.out_dir / ("alphashape-%s.qss" % theme)
        if args.check:
            current = raw_text(target) if target.exists() else None
            if current != text:
                print("stale: %s (run tools/theme/compile_qss.py)" % target, file=sys.stderr)
                stale = True
        else:
            args.out_dir.mkdir(parents=True, exist_ok=True)
            target.write_bytes(text.encode("utf-8"))
            print("wrote %s" % target)
    header = render_header(tokens, digest)
    if args.check:
        current = raw_text(args.header) if args.header.exists() else None
        if current != header:
            print("stale: %s (run tools/theme/compile_qss.py)" % args.header, file=sys.stderr)
            stale = True
    else:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_bytes(header.encode("utf-8"))
        print("wrote %s" % args.header)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
